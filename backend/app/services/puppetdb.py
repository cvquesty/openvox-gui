    async def get_pdb_metrics_bulk(self, names: Dict[str, str]) -> Dict[str, Any]:
        """One Jolokia POST for many mbeans. Fallback: per-bean GET."""
        out: Dict[str, Any] = {k: None for k in names}
        if not names:
            return out
        try:
            client = await self._get_client()
            # POST body uses real ObjectNames. !/ is only for GET URL paths.
            body = [
                {"type": "read", "mbean": unescape_jolokia_mbean(mbean)}
                for mbean in names.values()
            ]
            resp = await client.post("/metrics/v2/read", json=body)
            if resp.status_code == 200:
                payload = resp.json()
                rows = payload if isinstance(payload, list) else (
                    payload.get("value") if isinstance(payload, dict) else None
                )
                by_mbean: Dict[str, Any] = {}
                if isinstance(rows, list):
                    for row in rows:
                        if not isinstance(row, dict):
                            continue
                        req = row.get("request") or {}
                        mbean = req.get("mbean")
                        val = jolokia_row_value(row)
                        if mbean and val is not None:
                            by_mbean[normalize_mbean(str(mbean))] = val
                for key, mbean in names.items():
                    matched = by_mbean.get(normalize_mbean(mbean))
                    if matched is not None:
                        out[key] = matched
        except Exception as e:
            logger.warning("Jolokia bulk read failed: %s", e)
        missing = {k: m for k, m in names.items() if out.get(k) is None}
        if missing:
            async def _one(key: str, mbean: str) -> None:
                out[key] = (await self.get_pdb_metrics(mbean)).get("value")
            await asyncio.gather(*[_one(k, m) for k, m in missing.items()])
        return out

    async def get_report(self, report_hash: str) -> Dict:
        """Get a single report by hash (exact, then unique prefix).

        OpenVoxDB stores SHA-256 (64 hex). Older PuppetDB used SHA-1 (40).
        Operators and some UIs paste a prefix. Exact ``=`` misses those.
        On a clustered estate the ATLC console's OpenVoxDB may not have
        a PDXC-originated row yet — try configured peer OpenVoxDB hosts.
        """
        h = _validate_report_hash(report_hash)
        found = await self._lookup_report(h)
        if found:
            return found
        for peer in self._peer_puppetdb_hosts():
            try:
                found = await self._lookup_report_on_host(peer, h)
            except Exception as e:
                logger.warning("peer OpenVoxDB %s report lookup failed: %s", peer, e)
                continue
            if found:
                found["_openvoxdb_source"] = peer
                logger.info("report %s found on peer OpenVoxDB %s", h, peer)
                return found
        return {}

    def _peer_puppetdb_hosts(self) -> List[str]:
        try:
            from .cluster_config import load_cluster_config
            cfg = load_cluster_config()
        except Exception:
            cfg = {}
        primary = (settings.puppetdb_host or "").strip().lower()
        out: List[str] = []

        def _add(host: str) -> None:
            h = (host or "").strip().lower()
            if h and h != primary and h not in out:
                out.append(h)

        extra = getattr(settings, "puppetdb_peers", None) or ""
        for part in str(extra).replace(",", " ").split():
            _add(part)
        # Every configured OpenVoxDB member — VIP DNS RR can land on
        # different replicas; newest receive_time across members wins.
        for host in cfg.get("puppetdb_nodes") or []:
            _add(str(host))
        return out

    async def _query_host(
        self,
        host: str,
        endpoint: str,
        query: Optional[str] = None,
        params: Optional[Dict] = None,
    ) -> Any:
        """PuppetDB v4 query against an explicit peer FQDN."""
        port = settings.puppetdb_port
        if endpoint:
            url = f"https://{host}:{port}/pdb/query/v4/{endpoint}".rstrip("/")
        else:
            url = f"https://{host}:{port}/pdb/query/v4"
        request_params = dict(params or {})
        if query:
            request_params["query"] = query
        ctx = self._create_ssl_context()
        async with httpx.AsyncClient(
            verify=ctx,
            timeout=httpx.Timeout(4.0, connect=2.0),
            trust_env=False,
        ) as client:
            resp = await client.get(url, params=request_params)
            resp.raise_for_status()
            return resp.json()

    async def _latest_reports_from_host(self, host: str) -> Dict[str, Dict]:
        """Newest report per certname on one peer OpenVoxDB."""
        out: Dict[str, Dict] = {}
        pql = (
            "reports[certname, status, receive_time, start_time, end_time, "
            "hash, producer, cached_catalog_status, noop] { latest_report? = true }"
        )
        try:
            flagged = await self._query_host(
                host, "", query=pql, params={"limit": "5000"}
            ) or []
            for row in flagged:
                _fold_newest_report(out, row)
        except Exception as e:
            logger.warning("peer %s latest_report? failed: %s", host, e)
        # Same 48h projected window as the primary. A bare reports query
        # returns full documents (logs, metrics, events) — up to 2000 of
        # them per peer on every live-fleet rebuild.
        try:
            from datetime import datetime, timedelta, timezone

            cutoff = (
                datetime.now(timezone.utc) - timedelta(hours=48)
            ).strftime("%Y-%m-%dT%H:%M:%S.000Z")
            window = f'[">", "receive_time", "{cutoff}"]'
            ast = f'["extract", {self._LEAN_REPORT_FIELDS}, {window}]'
            recent = await self._query_host(
                host,
                "reports",
                query=ast,
                params={
                    "limit": "10000",
                    "order_by": '[{"field": "receive_time", "order": "desc"}]',
                },
            ) or []
            for row in _project_rows(recent, self._LEAN_REPORT_FIELDS):
                _fold_newest_report(out, row)
        except Exception as e:
            logger.warning(
                "peer %s lean recent reports failed (%s); falling back to full rows",
                host,
                e,
            )
            try:
                recent = await self._query_host(
                    host,
                    "reports",
                    params={
                        "limit": "2000",
                        "order_by": '[{"field": "receive_time", "order": "desc"}]',
                    },
                ) or []
                for row in recent:
                    _fold_newest_report(out, row)
            except Exception as e2:
                logger.warning("peer %s recent reports failed: %s", host, e2)
        return out

    async def _lookup_report(self, h: str) -> Dict:
        """Exact, then prefix, then PQL — against the primary OpenVoxDB."""
        results = await self._query(
            "reports",
            query=f'["=", "hash", "{h}"]',
        )
        if results:
            return results[0] if isinstance(results[0], dict) else {}
        if len(h) < 64:
            try:
                prefixed = await self.get_reports(
                    query=f'["~", "hash", "^{h}"]',
                    limit=20,
                    order_by="receive_time",
                    order_dir="desc",
                ) or []
                if prefixed and isinstance(prefixed[0], dict):
                    return prefixed[0]
            except Exception as e:
                logger.warning("prefix report lookup failed hash=%s: %s", h, e)
            try:
                rows = await self.pql(f'reports {{ hash ~ "^{h}" }}', limit=20) or []
                if rows and isinstance(rows[0], dict):
                    return rows[0]
            except Exception as e:
                logger.warning("PQL prefix report lookup failed hash=%s: %s", h, e)
        return {}

    async def _lookup_report_on_host(self, host: str, h: str) -> Dict:
        """Same lookup against a peer OpenVoxDB FQDN (clustered)."""
        url = f"https://{host}:{settings.puppetdb_port}/pdb/query/v4/reports"
        ctx = self._create_ssl_context()
        queries = [f'["=", "hash", "{h}"]']
        if len(h) < 64:
            queries.append(f'["~", "hash", "^{h}"]')
        async with httpx.AsyncClient(
            verify=ctx,
            timeout=httpx.Timeout(10.0, connect=4.0),
            trust_env=False,
        ) as client:
            for q in queries:
                resp = await client.get(
                    url,
                    params={
                        "query": q,
                        "limit": "20",
                        "order_by": '[{"field": "receive_time", "order": "desc"}]',
                    },
                )
                if resp.status_code >= 400:
                    continue
                rows = resp.json() or []
                if rows and isinstance(rows[0], dict):
                    return rows[0]
        return {}

