    async def pql(self, query: str, limit: int = 5000) -> Any:
        """Run a PQL query against /pdb/query/v4 (no trailing slash)."""
        client = await self._get_client()
        resp = await client.get(
            "/pdb/query/v4",
            params={"query": query, "limit": str(limit)},
        )
        resp.raise_for_status()
        return resp.json()

    async def get_latest_reports_by_certname(self) -> Dict[str, Dict]:
        """One newest report document per certname.

        ``latest_report?`` is a hint only. OpenVoxDB (especially a
        multi-writer / Spock mesh) can leave that flag on an older
        ``failed`` row after a later successful report is stored. Always
        merge a recent ``receive_time`` window and keep the newest row
        per exact certname. Do not put ``order by`` in PQL text —
        OpenVoxDB rejects it.
        """
        out: Dict[str, Dict] = {}

        try:
            flagged = await self.pql(
                "reports[certname, status, receive_time, start_time, end_time, "
                "hash, producer, cached_catalog_status, noop] { latest_report? = true }",
                limit=5000,
            ) or []
            for row in flagged:
                _fold_newest_report(out, row)
        except Exception as e:
            logger.warning("PQL latest_report? failed, trying AST: %s", e)
            try:
                flagged = await self.get_reports(
                    query='["=", "latest_report?", true]',
                    limit=5000,
                ) or []
                for row in flagged:
                    _fold_newest_report(out, row)
            except Exception as e2:
                logger.warning("AST latest_report? failed: %s", e2)

        # Last 48h via AST extract (HTTP order_by). Replaces a stuck
        # latest_report? flag. Unbounded "newest 2000" can miss a node
        # that reported once while others flooded the window.
        try:
            from datetime import datetime, timedelta, timezone

            cutoff = (
                datetime.now(timezone.utc) - timedelta(hours=48)
            ).strftime("%Y-%m-%dT%H:%M:%S.000Z")
            recent = await self.get_reports_lean(
                query=f'[">", "receive_time", "{cutoff}"]',
                limit=10000,
                order_by="receive_time",
                order_dir="desc",
            ) or []
            for row in recent:
                _fold_newest_report(out, row)
        except Exception as e:
            logger.warning("recent reports window failed: %s", e)

        # Dual-VIP: this console's ovdb.example.com A record is one site.
        # Merge newest receive_time from configured peer OpenVoxDBs so
        # Overview / Needs attention match the other console.
        try:
            peers = self._peer_puppetdb_hosts()
        except Exception:
            peers = []
        if peers:
            peer_maps = await asyncio.gather(
                *[self._latest_reports_from_host(h) for h in peers],
                return_exceptions=True,
            )
            for host, result in zip(peers, peer_maps):
                if isinstance(result, Exception):
                    logger.warning(
                        "peer OpenVoxDB %s latest reports failed: %s",
                        host,
                        result,
                    )
                    continue
                for row in (result or {}).values():
                    if not isinstance(row, dict):
                        continue
                    copied = dict(row)
                    copied["_openvoxdb_source"] = host
                    _fold_newest_report(out, copied)

        return out

    async def get_newest_report_for_certname(self, certname: str) -> Optional[Dict]:
        """Newest report for one certname by receive_time (not the node index)."""
        # Exact certname only — do not query bare "ovca1" (collides across sites).
        # OpenVoxDB rejects PQL ``order by``; use the AST reports endpoint.
        cn = (certname or "").strip()
        if not cn:
            return None
        safe = cn.replace("\\", "").replace('"', "")
        try:
            rows = await self.get_reports(
                query=f'["=", "certname", "{safe}"]',
                limit=50,
                order_by="receive_time",
                order_dir="desc",
            ) or []
        except Exception as e:
            logger.warning("newest report query failed certname=%s: %s", cn, e)
            rows = []
        best: Optional[Dict] = None
        for row in rows:
            if not isinstance(row, dict):
                continue
            if best is None or _report_ts(row) >= _report_ts(best):
                best = row
        try:
            peers = self._peer_puppetdb_hosts()
        except Exception:
            peers = []
        for host in peers:
            try:
                remote = await self._query_host(
                    host,
                    "reports",
                    query=f'["=", "certname", "{safe}"]',
                    params={
                        "limit": "50",
                        "order_by": '[{"field": "receive_time", "order": "desc"}]',
                    },
                ) or []
            except Exception as e:
                logger.warning(
                    "peer OpenVoxDB %s newest report failed certname=%s: %s",
                    host,
                    cn,
                    e,
                )
                continue
            for row in remote:
                if not isinstance(row, dict):
                    continue
                if best is None or _report_ts(row) >= _report_ts(best):
                    best = dict(row)
                    best["_openvoxdb_source"] = host
        return best

    async def _overlay_latest_report_status(self, nodes: List[Dict]) -> None:
        """Set display status from the newest report document, not the node index.

        PuppetDB report ``status`` is failed/changed/unchanged. The node-index
        field and ``latest_report?`` can stick on failed after a later
        successful report exists — we overlay the newest ``receive_time``.
        """
        if not nodes:
            return
        latest = await self.get_latest_reports_by_certname()
        for node in nodes:
            key = str(node.get("certname") or "").strip().lower()
            node["node_index_status"] = node.get("latest_report_status")
            row = _pick_report_for_node(key, latest)
            if not row:
                node["status_source"] = "node_index"
                continue
            status = row.get("status")
            if status:
                prev = node.get("latest_report_status")
                if prev != status:
                    logger.info(
                        "overlay latest report status certname=%s node_index=%s latest_report=%s hash=%s",
                        node.get("certname"),
                        prev,
                        status,
                        row.get("hash"),
                    )
                node["latest_report_status"] = status
            ts = row.get("end_time") or row.get("receive_time") or row.get("start_time")
            if ts:
                node["report_timestamp"] = ts
            node["latest_report_hash"] = row.get("hash")
            node["cached_catalog_status"] = row.get("cached_catalog_status")
            node["report_producer"] = row.get("producer")
            node["status_source"] = "latest_report"

